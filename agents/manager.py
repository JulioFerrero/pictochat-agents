import base64
import json
import os
import re
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "display"))
from pictochat_gui import decode_image                                                      # noqa: E402
from agents.claude_agent import (MESSAGE_TIME_FORMAT, STATE_DIR, SYSTEM, WEB_TOOLS,         # noqa: E402
                                 ClaudeSession, Room, image_block, log, member_nickname, picture_png,
                                 reply_pictures, save_capture, text_pictures)

REGISTRY = STATE_DIR / "registry.json"      # the agents and the trusted DSes (MAC -> nickname)
PC_HOME = Path(os.environ.get("PICTO_PC_HOME") or Path.home() / "PictoAgents")
PC_TOOLS = WEB_TOOLS + ["Bash", "Read", "Edit", "Write", "Glob", "Grep"]
GATED_TOOLS = [tool for tool in PC_TOOLS if tool not in WEB_TOOLS]     # the tool calls sent to gate.py
MAIN = "Claude"
ROUTER_MODEL = "claude-haiku-5-5"
INTERIM_AFTER = 12                    # seconds: an agent still busy after this says it is on it
# the DS favourite colours new agents get, in this order (the main agent is 4, pink)
AGENT_COLOURS = (11, 7, 13, 9, 3, 15, 5, 10, 14, 1, 0, 6, 8, 12, 2, 4)

ROUTER_SYSTEM = """You transcribe messages from a Nintendo DS PictoChat room. Each message is a picture: typed \
text, handwriting, a drawing, or a mix. The grid and rulers around it are not part of the message.
Reply with JSON only, no other text: {"text": "<every word written or typed, exactly, keeping symbols such as / \
and @ and keeping the line breaks as \\n, or empty>", "drawing": "<a few words describing any drawing, or empty>"}"""

AGENT_EXTRA = """

You are {name}, one of the AI agents in this room. {about}
Other agents here: {others}. People address you with @{name}; a message reaches you when it is for you.
Each message header says who sent it and whether their DS is trusted.

People run the room with commands written on the DS (they are handled before messages reach you):
@Name message (talk to one agent), /new Name what it does (a chat agent), /new Name pc what it does (an agent \
that works on the owner's Mac with a terminal and files, in ~/PictoAgents/Name; only trusted DSes can make or use \
one), /agents (who is here), /stop Name, /trust Nickname, /help.{self_tools}"""

# AGENT_EXTRA's {self_tools} for a chat agent
CHAT_AGENT_LIMITS = (" You yourself can't use the Mac (only search the web). If someone wants something done on the "
                     "Mac, tell them to make a PC agent, e.g. /new Coder pc writes code, then talk to it with @Coder.")

PC_EXTRA = """

You also work on the owner's Mac: your folder is {folder}. You have a terminal and can read and edit files there \
(and in other folders if you are told to). Only messages from trusted DSes can make you use the Mac; a Claude Code \
hook enforces this, so if a tool is blocked, say so in one short line. When you have done something, reply with \
the result in a few short lines, not the steps."""

# What PC agents put on their commits and pull requests (Claude Code's "attribution" setting). {agent} is the
# agent's name. pictoagents.json can change them: {"attribution": {"commit": "...", "pr": "..."}}.
ATTRIBUTION = {
    "commit": "Generated by {agent} with PictoChat x Claude Code, from a Nintendo DS\n\n"
              "Co-Authored-By: Claude <noreply@anthropic.com>",
    "pr": "\U0001F3AE Generated by {agent} with PictoChat x [Claude Code](https://claude.com/claude-code), "
          "from a Nintendo DS",
}


def attribution(agent):
    """ATTRIBUTION for one agent, with the texts pictoagents.json overrides."""
    overrides = {}
    try:
        overrides = json.loads((ROOT / "pictoagents.json").read_text()).get("attribution") or {}
    except (OSError, ValueError):
        pass
    return {key: str(overrides.get(key, default)).replace("{agent}", agent) for key, default in ATTRIBUTION.items()}


HELP = ("@Name message: talk to an agent. /new Name about: a new agent. /new Name pc about: one that works on "
        "the Mac. /agents: who is here. /stop Name. /trust Nick.")


def load_registry():
    """registry.json, or on the first start just the main agent and no trusted DS."""
    if REGISTRY.exists():
        return json.loads(REGISTRY.read_text())
    return {"agents": {MAIN: {"kind": "chat", "about": "You are the room's host and its first AI.", "colour": 4}},
            "trusted": {}}


def pc_settings(name):
    """Claude Code settings of a PC agent: its commit/PR attribution, and gate.py as a hook before every gated tool."""
    gate_command = "%s %s" % (sys.executable, ROOT / "agents" / "gate.py")
    return {"attribution": attribution(name),
            "hooks": {"PreToolUse": [{"matcher": "|".join(GATED_TOOLS),
                                      "hooks": [{"type": "command", "command": gate_command}]}]}}


class AgentRunner:
    """One agent: its Claude Code session, its inbox and what it is doing right now (for the screen)."""

    def __init__(self, manager, name, spec):
        self.manager, self.name, self.spec = manager, name, spec
        self.kind = spec.get("kind", "chat")
        self.status = {"state": "idle", "detail": "", "since": time.time(), "msgs": 0}
        self.inbox, self.inbox_ready, self.alive = [], threading.Condition(), True
        self.turn_file = STATE_DIR / (name + ".turn.json")       # who this turn answers, for gate.py
        tools, cwd, settings, env = WEB_TOOLS, None, None, {}
        if self.kind == "pc":
            folder = Path(spec["folder"]).expanduser()
            folder.mkdir(parents=True, exist_ok=True)
            tools, cwd, settings = PC_TOOLS, folder, pc_settings(name)
            env = {"PICTO_TURN": str(self.turn_file)}
        self.session = ClaudeSession(name, manager.args.model, manager.args.effort, system=self.system_prompt(),
                                     tools=tools, cwd=cwd, settings=settings, env=env, on_event=self.on_claude_event)
        threading.Thread(target=self.worker, daemon=True).start()

    def system_prompt(self):
        others = ", ".join(name for name in self.manager.agent_specs() if name != self.name) or "none yet"
        prompt = SYSTEM.format(name=self.name) + AGENT_EXTRA.format(
            name=self.name, about=self.spec.get("about", ""), others=others,
            self_tools="" if self.kind == "pc" else CHAT_AGENT_LIMITS)
        if self.kind == "pc":
            prompt += PC_EXTRA.format(folder=self.spec["folder"])
        return prompt

    def set_state(self, state, detail=""):
        if state != self.status["state"] or detail != self.status["detail"]:
            self.status.update(state=state, detail=detail, since=time.time())

    def on_claude_event(self, event):
        """Live status from Claude Code's stream: which tool it is using, or that it is writing."""
        if event.get("type") != "assistant":
            return
        for block in event.get("message", {}).get("content", []):
            if block.get("type") == "tool_use":
                tool_input = block.get("input") or {}
                subject = (tool_input.get("command") or tool_input.get("query") or tool_input.get("url")
                           or tool_input.get("file_path") or tool_input.get("pattern") or "")
                self.set_state("tool", "%s %s" % (block.get("name"), str(subject).replace("\n", " ")[:40]))
            elif block.get("type") == "text":
                self.set_state("writing", "writing a reply")

    def enqueue(self, item):
        with self.inbox_ready:
            self.inbox.append(item)
            self.inbox_ready.notify()

    def stop(self):
        self.alive = False
        with self.inbox_ready:
            self.inbox_ready.notify()
        self.session.stop()

    def worker(self):
        """Answers the inbox: what arrived while the agent was busy goes to Claude in one turn."""
        while self.alive:
            batch = self._take_batch()
            if batch is None:
                return
            self._write_turn_file(batch)
            self.set_state("thinking", "reading %s's message" % batch[-1]["nick"])
            reply = self._ask(batch)
            self.manager.say(self.name, reply, batch[-1].get("rows"))
            self.status["msgs"] += len(batch)
            self.set_state("idle")

    def _take_batch(self):
        """Waits for messages and takes them all; None once the agent is stopped."""
        with self.inbox_ready:
            while self.alive and not self.inbox:
                self.inbox_ready.wait()
            if not self.alive:
                return None
            batch, self.inbox = self.inbox, []
            return batch

    def _write_turn_file(self, batch):
        """Tells gate.py who this turn answers: the Mac tools run only if every message came from a trusted DS."""
        self.turn_file.write_text(json.dumps({
            "trusted": all(item["trusted"] for item in batch),
            "who": sorted({item["nick"] for item in batch}),
            "trusted_names": sorted(set(self.manager.registry["trusted"].values()))}) + "\n")

    @staticmethod
    def _turn_content(batch):
        """The user turn: for each message a header (sender, trusted or not, local time, what the router read) and
        the picture."""
        content = []
        for item in batch:
            header = "%s (%s DS), %s" % (item["nick"], "trusted" if item["trusted"] else "untrusted",
                                         time.strftime(MESSAGE_TIME_FORMAT, item["when"]))
            if item.get("text"):
                header += '. It reads: "%s"' % item["text"]
            content.append({"type": "text", "text": header + ":"})
            content.append(image_block(item["png_b64"]))
        return content

    def _ask(self, batch):
        """Claude's reply to a batch (or an error note for the room); says it is working on it if that takes long."""
        content = self._turn_content(batch)
        done = threading.Event()
        threading.Thread(target=self.announce_if_slow, args=(done,), daemon=True).start()
        started = time.time()
        try:
            prompt = self.system_prompt()
            if prompt != self.session.system:   # other agents came or went: Claude Code reads its prompt only
                self.session.system = prompt    # when it starts, so start it again (it resumes the conversation)
                self.session.stop()
            reply = self.session.ask(content)
        except Exception as error:
            log("%s: error: %s" % (self.name, error))
            reply = "(error: %s)" % str(error)[:80]
        done.set()
        log("%s: %.1fs -> %r" % (self.name, time.time() - started, reply[:100]))
        return reply

    def announce_if_slow(self, done):
        """A long job (PC agents, web searches): tell the room once that the agent is on it. Only the kind of work:
        commands and paths stay on the status screen, since anyone can be in the room."""
        if not done.wait(INTERIM_AFTER):
            tool = (self.status["detail"] or "").split(" ")[0] if self.status["state"] == "tool" else ""
            self.manager.say(self.name, "working on it... (%s)" % ACTIVITY.get(tool, "thinking"))


# What the room is told an agent is doing, by Claude Code tool
ACTIVITY = {"Bash": "using the terminal", "Read": "reading files", "Glob": "looking through files",
            "Grep": "searching files", "Edit": "editing files", "Write": "writing files",
            "WebSearch": "searching the web", "WebFetch": "reading a web page"}


class Manager:
    """The room's agents: every picture goes through the router, then to a command or to an agent, whose reply goes
    back to the room. Also feeds the status screen and logs/status.json."""

    screen_state = None     # display/room_display.RoomState (set by run): members, radio, as the host reports them

    def __init__(self, args):
        self.args = args
        self.registry = load_registry()
        for mac in args.trust or []:
            self.registry["trusted"].setdefault(mac.lower(), "owner")
        self.save_registry()
        self.nicknames, self.macs = {}, {}      # sender id -> nickname / MAC
        self.last_target = {}                   # sender MAC -> agent name it last talked to
        self.room = None
        self.agents = {}                        # name -> AgentRunner
        self.route_queue, self.route_ready = [], threading.Condition()
        self.router = ClaudeSession("_router", ROUTER_MODEL, "low", system=ROUTER_SYSTEM, tools=[])
        for name, spec in self.registry["agents"].items():
            self.agents[name] = AgentRunner(self, name, spec)
        threading.Thread(target=self.route_worker, daemon=True).start()

    def agent_specs(self):
        return self.registry["agents"]

    def save_registry(self):
        STATE_DIR.mkdir(parents=True, exist_ok=True)
        REGISTRY.write_text(json.dumps(self.registry, indent=1) + "\n")

    def find_agent(self, name):
        """The agent with this name (any case), or the only one whose name starts with it; else None."""
        name = name.lower()
        for agent in self.agents:
            if agent.lower() == name:
                return agent
        matches = [agent for agent in self.agents if agent.lower().startswith(name)]
        return matches[0] if len(matches) == 1 else None

    # ---------------------------------------------------------------- talking to the room
    def say(self, agent, text, last_rows=None):
        """An agent's reply (text and ```draw blocks) into the room, from the agent's own member: the main agent is
        the host itself, the others are virtual members of the room (see join_room)."""
        if agent != MAIN and not self.args.members:          # one voice: replies start with the agent's name
            text = re.sub(r"^(?!```)", agent + ": ", text.lstrip(), count=1)
        for rows in reply_pictures(text, last_rows):
            try:
                command = {"cmd": "chat", "pixels": rows}
                if agent != MAIN and self.args.members:
                    command["as"] = agent
                self.room.send(command)
            except (OSError, AttributeError) as error:
                log("room: reply lost (%s)" % error)

    def system_say(self, text):
        """The manager's own answer to a command, from the host's member."""
        log("system: %s" % text)
        for rows in text_pictures(text):
            try:
                self.room.send({"cmd": "chat", "pixels": rows})
            except (OSError, AttributeError) as error:
                log("room: message lost (%s)" % error)

    def join_room(self, name):
        """The agent becomes a member of the room: every DS sees it enter, with its name and colour."""
        if name != MAIN and self.room is not None and self.args.members:
            try:
                self.room.send({"cmd": "member_add", "name": name,
                                "color": self.registry["agents"][name].get("colour", 0)})
            except OSError as error:
                log("room: %s could not join (%s)" % (name, error))

    def leave_room(self, name):
        if name != MAIN and self.room is not None and self.args.members:
            try:
                self.room.send({"cmd": "member_remove", "name": name})
            except OSError as error:
                log("room: %s could not leave (%s)" % (name, error))

    # ---------------------------------------------------------------- events from the host
    def on_event(self, event, live):
        """Every event from the host: who is who (sender ids, MACs, nicknames), and each new picture from a DS goes
        to the router."""
        if self.screen_state is not None:
            self.screen_state.on_event(event, live)
        kind = event.get("kind")
        if kind == "state":
            for mac, aid in (event.get("aids") or {}).items():      # a DS's AID is its sender id
                self.macs[aid] = mac.lower()
            return
        if kind != "message" or event.get("dir") != "rx":
            return
        sender_id = event.get("id")
        if event.get("mac"):
            self.macs[sender_id] = event["mac"].lower()
        message = bytes.fromhex(event.get("hex", ""))
        nickname = member_nickname(message)
        if nickname is not None:
            self.nicknames[sender_id] = nickname
            return
        rows = decode_image(message)
        if rows is None or not live:
            return
        self._queue_picture(sender_id, rows)

    def _queue_picture(self, sender_id, rows):
        """Queue a DS's picture for the router, with who sent it and whether that DS is trusted."""
        mac = self.macs.get(sender_id, "")
        nickname = self.nicknames.get(sender_id, "someone")
        png = picture_png(rows)
        save_capture(png, nickname)
        trusted_macs = self.registry["trusted"]
        if mac in trusted_macs and trusted_macs[mac] != nickname and nickname != "someone":   # a trusted DS renamed
            trusted_macs[mac] = nickname
            self.save_registry()
        item = {"nick": nickname, "mac": mac, "trusted": mac in trusted_macs, "rows": rows,
                "png_b64": base64.b64encode(png).decode(), "when": time.localtime()}
        log("room: picture from %s (%s%s)" % (nickname, mac or "?", ", trusted" if item["trusted"] else ""))
        with self.route_ready:
            self.route_queue.append(item)
            self.route_ready.notify()

    # ---------------------------------------------------------------- routing and commands
    def transcribe(self, item):
        """What the router reads in a picture: (text, description of any drawing), both "" if it fails."""
        try:
            answer = self.router.ask([image_block(item["png_b64"])])
            json_text = re.search(r"\{.*\}", answer, re.S)
            data = json.loads(json_text.group(0)) if json_text else {}
            return (data.get("text") or "").strip(), (data.get("drawing") or "").strip()
        except Exception as error:
            log("router: %s" % error)
            return "", ""

    def route_worker(self):
        while True:
            with self.route_ready:
                while not self.route_queue:
                    self.route_ready.wait()
                item = self.route_queue.pop(0)
            started = time.time()
            item["text"], item["drawing"] = self.transcribe(item)
            log("router: %.1fs %r%s" % (time.time() - started, item["text"][:60],
                                        " + drawing: " + item["drawing"][:40] if item["drawing"] else ""))
            try:
                self.route(item)
            except Exception as error:
                log("route: %s" % error)

    def route(self, item):
        """One picture can hold several commands: a new part starts at each line beginning with / or @."""
        parts, current = [], []
        for line in item["text"].splitlines() or [""]:
            if line.strip()[:1] in ("/", "@") and current:
                parts.append(" ".join(current))
                current = []
            current.append(line.strip())
        parts.append(" ".join(current).strip())
        for part in parts:
            self.route_one(dict(item, text=part))

    def route_one(self, item):
        """A command, or a message for the agent it @mentions, else for the agent this DS last talked to."""
        text = item["text"]
        if text.startswith("/"):
            return self.command(item, text)
        mention = re.match(r"@\s*([A-Za-z0-9_\-]+)[,:]?\s*(.*)", text, re.S)
        if mention:
            target = self.find_agent(mention.group(1))
            if not target:
                return self.system_say("No agent called %s here. /agents lists them, /new %s makes one."
                                       % (mention.group(1), mention.group(1)))
            self.last_target[item["mac"]] = target
        else:
            target = self.last_target.get(item["mac"], MAIN)
            if target not in self.agents:
                target = MAIN
        self.agents[target].enqueue(item)

    def command(self, item, text):
        words = text[1:].split()
        command_name = words[0].lower() if words else ""
        if command_name in ("agents", "list", "who"):
            return self._list_agents()
        if command_name == "help":
            return self.system_say(HELP)
        if command_name == "new" and len(words) >= 2:
            return self._new_agent(item, words[1], words[2:])
        if command_name in ("stop", "delete", "remove") and len(words) >= 2:
            return self._stop_agent(item, words[1])
        if command_name == "trust" and len(words) >= 2:
            return self._trust(item, words[1])
        return self.system_say("Unknown command. " + HELP)

    def _list_agents(self):
        """/agents: each agent and what it is doing."""
        lines = ["%s%s: %s" % (name, " (PC)" if runner.kind == "pc" else "",
                               runner.status["detail"] or runner.status["state"])
                 for name, runner in self.agents.items()]
        return self.system_say("\n".join(lines) or "No agents.")

    def _new_agent(self, item, requested_name, about_words):
        """/new Name [pc] what it does: a chat agent, or a PC agent when a trusted DS asks for one. An agent of the
        same name is remade with the new settings and a fresh session (by a trusted DS or whoever made it)."""
        trusted, nickname = item["trusted"], item["nick"]
        name = re.sub(r"[^A-Za-z0-9_\-]", "", requested_name)[:10]
        name = name[:1].upper() + name[1:]
        if about_words and about_words[0].lower() in ("pc", "mac", "computer"):
            about_words = about_words[1:]
            wants_pc = True
        else:                              # "helps with my mac", "uses the computer"...
            wants_pc = bool(re.search(r"\b(pc|mac|macbook|computer|ordenador|terminal)\b", " ".join(about_words),
                                      re.I))
        kind = "pc" if wants_pc and trusted else "chat"
        if not name:
            return self.system_say("Give it a name: /new Name what it does")
        existing = self.find_agent(name)
        if existing and existing.lower() == name.lower():
            if existing == MAIN:
                return self.system_say("%s is the room's host; pick another name." % MAIN)
            if not trusted and self.registry["agents"][existing].get("created_by") != nickname:
                return self.system_say("%s is already here." % existing)
            self.agents.pop(existing).stop()            # remade with the new settings and a fresh session
            del self.registry["agents"][existing]
            (STATE_DIR / (existing + ".json")).unlink(missing_ok=True)
            self.leave_room(existing)
        if wants_pc and not trusted:
            note = " (a chat agent: only a trusted DS can make one that uses the Mac)"
        else:
            note = ""
        used = {spec.get("colour") for spec in self.registry["agents"].values()}
        colour = next((candidate for candidate in AGENT_COLOURS if candidate not in used), 0)
        spec = {"kind": kind, "about": " ".join(about_words) or "A friendly helper.", "colour": colour,
                "created_by": nickname}
        if kind == "pc":
            spec["folder"] = str(PC_HOME / name)
        self.registry["agents"][name] = spec
        self.save_registry()
        self.agents[name] = AgentRunner(self, name, spec)
        self.join_room(name)
        self.last_target[item["mac"]] = name
        where = " It can use the Mac, in ~/PictoAgents/%s." % name if kind == "pc" else ""
        return self.system_say("%s joined!%s%s Talk to it with @%s." % (name, where, note, name))

    def _stop_agent(self, item, requested_name):
        """/stop Name: anyone can remove a chat agent, only a trusted DS a PC agent; the main agent stays."""
        name = self.find_agent(requested_name)
        if not name or name == MAIN:
            return self.system_say("Can't stop %s." % requested_name)
        if self.registry["agents"][name].get("kind") == "pc" and not item["trusted"]:
            return self.system_say("Only a trusted DS can stop %s." % name)
        self.agents.pop(name).stop()
        del self.registry["agents"][name]
        self.save_registry()
        (STATE_DIR / (name + ".json")).unlink(missing_ok=True)       # a later /new Name starts a new conversation
        self.leave_room(name)
        return self.system_say("%s has left the room." % name)

    def _trust(self, item, nickname):
        """/trust Nickname: a trusted DS vouches for another DS in the room, which is then known by its MAC."""
        if not item["trusted"]:
            return self.system_say("Only a trusted DS can trust others.")
        matches = [(sender_id, name) for sender_id, name in self.nicknames.items()
                   if name.lower() == nickname.lower() and sender_id in self.macs]
        if not matches:
            return self.system_say("Nobody called %s is in the room." % nickname)
        sender_id, name = matches[0]
        self.registry["trusted"][self.macs[sender_id]] = name
        self.save_registry()
        return self.system_say("%s's DS is trusted now: its messages can use the Mac." % name)

    # ---------------------------------------------------------------- status screen and status.json
    def agent_rows(self):
        """The agents as the status screen and status.json show them."""
        agents = list(self.agents.items())               # a copy: /new and /stop change the dict meanwhile
        return [dict(name=name, colour=self.registry["agents"].get(name, {}).get("colour", 0), kind=runner.kind,
                     **runner.status)
                for name, runner in agents]

    def screen_loop(self, profile):
        """Draws the status screen (display/dashboard.py) on the modem board every half second."""
        from room_display import ModemScreen
        import dashboard
        screen = ModemScreen(lambda: self.room, profile)
        set_up_on = None                            # the Room connection the screen was last set up through
        while True:
            try:
                if set_up_on is not self.room:      # first time, and after every reconnect (the modem may
                    time.sleep(1)                   # have restarted with the host)
                    screen.init()
                    set_up_on = self.room
                screen.show(dashboard.render(self.screen_state, self.agent_rows(), set(self.registry["trusted"])))
            except Exception as error:
                log("screen: %s" % error)
                time.sleep(2)
            time.sleep(0.5)

    def status_report(self):
        """The room, the radio, the people and the agents, as logs/status.json has them."""
        room_state = self.screen_state
        with room_state.lock:
            people = {str(member_id): member for member_id, member in room_state.members.items()
                      if member_id and not member.get("agent")}
            mac_of = {str(aid): mac for mac, aid in room_state.aids.items()}
            radio = {"rssi": room_state.rssi, "answered": room_state.answered, "radio": room_state.radio}
        return {"time": time.time(), "connected": self.room is not None, "radio": radio,
                "people": [dict(member, mac=mac_of.get(member_id, ""),
                                trusted=mac_of.get(member_id, "") in self.registry["trusted"])
                           for member_id, member in people.items()],
                "agents": self.agent_rows()}

    def status_loop(self):
        """logs/status.json every 2 s: what `pictoagents status` (or a UI) shows."""
        path = ROOT / "logs" / "status.json"
        path.parent.mkdir(exist_ok=True)
        while True:
            try:
                temporary = path.with_suffix(".tmp")
                temporary.write_text(json.dumps(self.status_report(), indent=1) + "\n")
                temporary.replace(path)
            except Exception as error:                   # never let the status file stop for good
                log("status: %s" % error)
            time.sleep(2)

    def run(self):
        """Connects to the host and handles its events, reconnecting whenever the connection drops."""
        from room_display import RoomState
        self.screen_state = RoomState()
        threading.Thread(target=self.status_loop, daemon=True).start()
        if self.args.screen:
            threading.Thread(target=self.screen_loop, args=(self.args.screen,), daemon=True).start()
        while True:
            try:
                self.room = Room(self.args.port)
                self.room.send({"cmd": "set_name", "name": MAIN})
                for name in self.agents:                 # (the host ignores agents that are members already)
                    self.join_room(name)
                log("manager: connected, agents: %s" % ", ".join(self.agents))
                for event, live in self.room.events():
                    self.on_event(event, live)
            except OSError as error:
                log("room: %s; reconnecting in 2 s" % error)
                time.sleep(2)


