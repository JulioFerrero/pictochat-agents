#!/usr/bin/env python3
"""Several AI agents in the PictoChat room, run from the DS.

    .venv/bin/python agents/manager.py --trust 00:09:bf:12:34:56 --screen waveshare-s3-lcd2

Every picture from a DS is first read by a small fast model (the router), so commands work typed or handwritten:
    @Name message              talk to one agent; after that, your messages go to it until you @ another one
    /new Name what it does     a chat agent (web search)
    /new Name pc what it does  a PC agent: works on the Mac in ~/PictoAgents/Name (trusted DSes only)
    /agents                    who is here and what each one is doing
    /stop Name                 remove an agent
    /trust Nickname            trust that DS too (trusted DSes only)
    /help
Each agent is its own Claude Code session (your subscription; see claude_agent.py), with its own name, colour, tools
and folder. The agents and the trusted DSes are kept in agents/state/registry.json.

PC tools (terminal, files) are gated by agents/gate.py, a Claude Code hook: they run only when every message the
agent is answering came from a trusted DS, recognised by its hardware (MAC) address, not its nickname. Before each
turn the manager writes who the agent is answering to agents/state/<Name>.turn.json, which the hook reads.

The manager also keeps logs/status.json up to date (for `pictoagents status`) and, with --screen, draws a status
screen on the radio board (display/dashboard.py).
"""
